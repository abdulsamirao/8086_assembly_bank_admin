.code
; Purpose: Establish the DOS segments, save the PSP and timer vector, then parse
;          product command switches.
; Inputs: DOS command tail at the PSP offset 80h and current INT 1Ch vector.
; Outputs: Prints the product-shell response and exits DOS.
; Registers: Destroys AX, BX, CX, DX, SI, DI, ES; preserves none.
; Flags: Unspecified on return to DOS.
; ISA: INT 21h/AH=62h, segment initialization, near CALL, and direct addressing.
MAIN PROC
    MOV AH, 62h
    INT 21h
    MOV SI, BX

    MOV AX, @DATA
    MOV DS, AX
    MOV ES, AX
    MOV PSP_SEGMENT, SI
    CLD
    CALL ISR_SAVE_VECTOR

    CALL PARSE_COMMAND
    CMP PARSE_STATUS, 0
    JE MAIN_PARSE_OK
    JMP MAIN_PARSE_ERROR

MAIN_PARSE_OK:
    CMP SWITCH_KIND, 'T'
    JE MAIN_LOAD_DATA
    CMP SWITCH_KIND, 'I'
    JE MAIN_INIT
    CMP SWITCH_KIND, 'B'
    JE MAIN_BENCH
    CMP SWITCH_KIND, 0
    JNE MAIN_USAGE
MAIN_LOAD_DATA:
    CALL DATA_LOAD
    CMP AL, 0
    JE MAIN_DATA_LOADED
    CMP AL, 1
    JE MAIN_DATA_MISSING
    JMP MAIN_DATA_NOT_MISSING
MAIN_DATA_MISSING:
    MOV DX, OFFSET MSG_DATA_MISSING
    CALL PRINT_STRING
    MOV AX, 4C03h
    INT 21h
MAIN_DATA_NOT_MISSING:
    CMP AL, 2
    JE MAIN_DATA_CORRUPT
    JMP MAIN_DATA_IO_ERROR
MAIN_DATA_CORRUPT:
    MOV DX, OFFSET MSG_DATA_CORRUPT
    CALL PRINT_STRING
    MOV AX, 4C03h
    INT 21h
MAIN_DATA_IO_ERROR:
    MOV DX, OFFSET MSG_DATA_IO
    CALL PRINT_STRING
    MOV AX, 4C03h
    INT 21h
MAIN_DATA_LOADED:
    CALL ADMIN_RUN
    MOV AH, 4Ch
    INT 21h

MAIN_USAGE:
    MOV DX, OFFSET MSG_USAGE
    CALL PRINT_STRING
    JMP MAIN_EXIT_OK

MAIN_INIT:
    CALL DATA_INIT
    CMP AL, 0
    JE MAIN_INIT_DONE
    MOV DX, OFFSET MSG_INIT_FAIL
    CALL PRINT_STRING
    MOV AX, 4C03h
    INT 21h
MAIN_INIT_DONE:
    MOV DX, OFFSET MSG_INIT
    CALL PRINT_STRING
    JMP MAIN_EXIT_OK

MAIN_BENCH:
    CALL BENCH_RUN
    CMP AL, 0
    JE MAIN_BENCH_DONE
    MOV DX, OFFSET MSG_BENCH_FAIL
    CALL PRINT_STRING
    MOV AX, 4C01h
    INT 21h
MAIN_BENCH_DONE:
    MOV DX, OFFSET MSG_BENCH_DONE
    CALL PRINT_STRING
    MOV DX, OFFSET MSG_BENCH_VALUE
    CALL PRINT_STRING
    MOV DX, OFFSET BENCH_BINARY_TEXT
    CALL PRINT_STRING
    CALL PRINT_NEWLINE
    JMP MAIN_EXIT_OK

MAIN_PARSE_ERROR:
    MOV DX, OFFSET MSG_UNKNOWN
    CALL PRINT_STRING
    MOV AX, 4C01h
    INT 21h

MAIN_EXIT_OK:
    MOV AX, 4C00h
    INT 21h

MAIN_EXIT:
    MOV AL, NUMBER_STATUS
    MOV AH, 4Ch
    INT 21h
MAIN ENDP

