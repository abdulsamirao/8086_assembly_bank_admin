; Purpose: Save the PSP segment and dispatch one requested I/O regression.
; Inputs: DOS command tail contains /T followed by a test selector.
; Outputs: Prints the selected result and exits with its status.
; Registers: Destroys AX, BX, CX, DX, SI, DI, ES; preserves none.
; Flags: Unspecified on return to DOS.
; ISA: INT 21h/AH=62h, REP MOVSB, CALL, PUSH/POP, and segment setup.
MAIN PROC
    MOV AH, 62h
    INT 21h
    MOV SI, BX

    MOV AX, @DATA
    MOV DS, AX
    MOV ES, AX
    MOV PSP_SEGMENT, SI
    CLD

    CALL PARSE_COMMAND
    CMP PARSE_STATUS, 0
    JNE TDRV_BAD_COMMAND
    CMP SWITCH_KIND, 'T'
    JNE TDRV_BAD_COMMAND

    CALL NEXT_TOKEN
    JC TDRV_DISPATCH
    MOV SI, OFFSET TOKEN_BUFFER
    MOV DI, OFFSET TEST_OPERATION
    MOV CX, 33
    PUSH ES
    PUSH DS
    POP ES
    REP MOVSB
    POP ES

TDRV_DISPATCH:
    CALL RUN_IO_TEST
    MOV AL, NUMBER_STATUS
    MOV AH, 4Ch
    INT 21h

TDRV_BAD_COMMAND:
    MOV DX, OFFSET MSG_UNKNOWN_SWITCH
    CALL PRINT_STRING
    MOV AX, 4C01h
    INT 21h
MAIN ENDP

