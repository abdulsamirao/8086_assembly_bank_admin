; Purpose: Check the documented seed-account hash against its independent value.
; Inputs: DATA_TEST_ID and DATA_TEST_PIN contain four ASCII digits each.
; Outputs: Prints HASH=<unsigned decimal word>; NUMBER_STATUS is the exit status.
; Registers: Destroys AX; DATA_TEST_PIN is cleared by PIN_HASH.
; Flags: Unspecified.
; ISA: CALL and unsigned decimal output.
TEST_PIN_HASH PROC NEAR
    MOV SI, OFFSET DATA_TEST_ID
    MOV DI, OFFSET DATA_TEST_PIN
    CALL PIN_HASH
    MOV NUMBER_VALUE, AX
    MOV DX, OFFSET MSG_HASH_PREFIX
    CALL PRINT_STRING
    MOV AX, NUMBER_VALUE
    CALL PRINT_DECIMAL
    CALL PRINT_NEWLINE
    MOV NUMBER_STATUS, 0
    RET
TEST_PIN_HASH ENDP

; Purpose: Check matching and mismatching seed PINs through PIN_VERIFY.
; Inputs: DATA_TEST_ID, DATA_TEST_PIN, and the documented admin hash.
; Outputs: Prints VERIFY OK when match and mismatch results are correct.
; Registers: Destroys AX, BX, CX, DX, SI, DI; preserves other registers.
; Flags: Unspecified.
; ISA: CALL, CMP, conditional branches, and direct memory addressing.
TEST_PIN_VERIFY PROC NEAR
    MOV SI, OFFSET DATA_TEST_ID
    MOV DI, OFFSET DATA_TEST_PIN
    MOV BX, 3E3Dh
    CALL PIN_VERIFY
    CMP AL, 1
    JNE TEST_PIN_VERIFY_BAD
    MOV BYTE PTR DATA_TEST_PIN, '1'
    MOV BYTE PTR DATA_TEST_PIN+1, '3'
    MOV BYTE PTR DATA_TEST_PIN+2, '5'
    MOV BYTE PTR DATA_TEST_PIN+3, '8'
    MOV SI, OFFSET DATA_TEST_ID
    MOV DI, OFFSET DATA_TEST_PIN
    MOV BX, 3E3Dh
    CALL PIN_VERIFY
    CMP AL, 0
    JNE TEST_PIN_VERIFY_BAD
    MOV DX, OFFSET MSG_VERIFY_OK
    CALL PRINT_STRING
    MOV NUMBER_STATUS, 0
    RET
TEST_PIN_VERIFY_BAD:
    MOV DX, OFFSET MSG_DATA_TEST_BAD
    CALL PRINT_STRING
    MOV NUMBER_STATUS, 1
    RET
TEST_PIN_VERIFY ENDP

