; Purpose: Prove that a changed checksum is rejected as corrupt data.
; Inputs: None; the procedure creates and then damages the seed file.
; Outputs: Prints CORRUPT DETECTED only for the expected corruption status.
; Registers: Destroys AX, BX, CX, DX, SI; preserves DI, BP, DS, ES.
; Flags: Unspecified.
; ISA: INT 21h/AH=3Dh, AH=40h, AH=41h, and AH=42h.
TEST_DATA_CORRUPT PROC NEAR
    CALL DATA_INIT
    OR AL, AL
    JNZ TEST_DATA_CORRUPT_BAD
    MOV DX, OFFSET DATA_FILE_NAME
    MOV AX, 3D02h
    INT 21h
    JC TEST_DATA_CORRUPT_BAD
    MOV DATA_HANDLE, AX
    MOV BX, AX
    XOR CX, CX
    MOV DX, DATA_LENGTH
    DEC DX
    MOV AX, 4200h
    INT 21h
    JC TEST_DATA_CORRUPT_CLOSE_BAD
    MOV SI, OFFSET DATA_IMAGE
    ADD SI, DATA_LENGTH
    DEC SI
    XOR BYTE PTR [SI], 1
    MOV DX, SI
    MOV CX, 1
    MOV AH, 40h
    INT 21h
    JC TEST_DATA_CORRUPT_CLOSE_BAD
    CMP AX, 1
    JNE TEST_DATA_CORRUPT_CLOSE_BAD
    MOV BX, DATA_HANDLE
    MOV AH, 3Eh
    INT 21h
    JC TEST_DATA_CORRUPT_BAD
    CALL DATA_LOAD
    CMP AL, 2
    JNE TEST_DATA_CORRUPT_BAD
    MOV DX, OFFSET DATA_FILE_NAME
    MOV AH, 41h
    INT 21h
    MOV DX, OFFSET MSG_CORRUPT_OK
    CALL PRINT_STRING
    MOV NUMBER_STATUS, 0
    RET
TEST_DATA_CORRUPT_CLOSE_BAD:
    MOV BX, DATA_HANDLE
    MOV AH, 3Eh
    INT 21h
TEST_DATA_CORRUPT_BAD:
    MOV DX, OFFSET DATA_FILE_NAME
    MOV AH, 41h
    INT 21h
    MOV DX, OFFSET MSG_DATA_TEST_BAD
    CALL PRINT_STRING
    MOV NUMBER_STATUS, 1
    RET
TEST_DATA_CORRUPT ENDP

