; Purpose: Dispatch the test routine named after the /T switch.
; Inputs: TEST_OPERATION and any remaining PSP tail tokens.
; Outputs: Prints one deterministic result and stores its return status.
; Registers: Destroys AX, BX, CX, DX, SI, DI; preserves DS and ES.
; Flags: Unspecified.
; ISA: REPE CMPSB-backed token matching and DOS interrupt-driven I/O.
RUN_IO_TEST PROC NEAR
    MOV SI, OFFSET TEST_OPERATION
    MOV DI, OFFSET OP_STRING
    MOV CX, 7
    CALL TOKEN_EQUALS
    JNE TEST_NOT_STRING
    JMP TEST_STRING

TEST_NOT_STRING:
    MOV SI, OFFSET TEST_OPERATION
    MOV DI, OFFSET OP_CHAR
    MOV CX, 5
    CALL TOKEN_EQUALS
    JNE TEST_NOT_CHAR
    JMP TEST_CHAR

TEST_NOT_CHAR:
    MOV SI, OFFSET TEST_OPERATION
    MOV DI, OFFSET OP_NEWLINE
    MOV CX, 8
    CALL TOKEN_EQUALS
    JNE TEST_NOT_NEWLINE
    JMP TEST_NEWLINE

TEST_NOT_NEWLINE:
    MOV SI, OFFSET TEST_OPERATION
    MOV DI, OFFSET OP_LINE
    MOV CX, 5
    CALL TOKEN_EQUALS
    JNE TEST_NOT_LINE
    JMP TEST_LINE

TEST_NOT_LINE:
    MOV SI, OFFSET TEST_OPERATION
    MOV DI, OFFSET OP_TWOLINE
    MOV CX, 8
    CALL TOKEN_EQUALS
    JNE TEST_NOT_TWOLINE
    JMP TEST_TWOLINE

TEST_NOT_TWOLINE:
    MOV SI, OFFSET TEST_OPERATION
    MOV DI, OFFSET OP_PIN
    MOV CX, 4
    CALL TOKEN_EQUALS
    JNE TEST_NOT_PIN
    JMP TEST_PIN

TEST_NOT_PIN:
    MOV SI, OFFSET TEST_OPERATION
    MOV DI, OFFSET OP_ACCTPIN
    MOV CX, 8
    CALL TOKEN_EQUALS
    JNE TEST_NOT_ACCTPIN
    JMP TEST_ACCTPIN

TEST_NOT_ACCTPIN:
    MOV SI, OFFSET TEST_OPERATION
    MOV DI, OFFSET OP_DECIMAL
    MOV CX, 8
    CALL TOKEN_EQUALS
    JNE TEST_NOT_DECIMAL
    JMP TEST_DECIMAL

TEST_NOT_DECIMAL:
    MOV SI, OFFSET TEST_OPERATION
    MOV DI, OFFSET OP_PSP
    MOV CX, 4
    CALL TOKEN_EQUALS
    JNE TEST_NOT_PSP
    JMP TEST_PSP

TEST_NOT_PSP:
    MOV SI, OFFSET TEST_OPERATION
    MOV DI, OFFSET OP_BCD
    MOV CX, 4
    CALL TOKEN_EQUALS
    JNE TEST_UNKNOWN
    JMP TEST_BCD

TEST_UNKNOWN:
    MOV DX, OFFSET MSG_UNKNOWN_TEST
    CALL PRINT_STRING
    MOV NUMBER_STATUS, 1
    RET

TEST_STRING:
    MOV DX, OFFSET MSG_STRING
    CALL PRINT_STRING
    XOR AL, AL
    MOV NUMBER_STATUS, AL
    RET

TEST_CHAR:
    MOV DL, MSG_CHAR
    CALL PRINT_CHAR
    CALL PRINT_NEWLINE
    XOR AL, AL
    MOV NUMBER_STATUS, AL
    RET

TEST_NEWLINE:
    CALL PRINT_NEWLINE
    XOR AL, AL
    MOV NUMBER_STATUS, AL
    RET

TEST_LINE:
    CALL READ_LINE
    MOV LINE_STATUS, AL
    MOV NUMBER_STATUS, AL
    CMP AL, 1
    JE TEST_LINE_EOF
    CMP AL, 2
    JE TEST_LINE_LONG
    JMP TEST_PRINT_LINE

TEST_TWOLINE:
    CALL READ_LINE
    OR AL, AL
    JNZ TEST_INPUT_ERROR
    CALL TEST_PRINT_LINE
    CALL READ_LINE
    OR AL, AL
    JNZ TEST_INPUT_ERROR
    CALL TEST_PRINT_LINE
    XOR AL, AL
    MOV NUMBER_STATUS, AL
    RET

TEST_PRINT_LINE:
    MOV DX, OFFSET MSG_LINE_PREFIX
    CALL PRINT_STRING
    MOV DX, OFFSET LINE_BUFFER+2
    MOV AH, 09h
    INT 21h
    CALL PRINT_NEWLINE
    RET

TEST_INPUT_ERROR:
    MOV LINE_STATUS, AL
    MOV NUMBER_STATUS, AL
    CMP AL, 1
    JE TEST_LINE_EOF
    JMP TEST_LINE_LONG

TEST_LINE_EOF:
    MOV DX, OFFSET MSG_LINE_EOF
    CALL PRINT_STRING
    RET

TEST_LINE_LONG:
    MOV DX, OFFSET MSG_LINE_LONG
    CALL PRINT_STRING
    RET

TEST_PIN:
    CALL READ_PIN
    MOV PIN_STATUS, AL
    MOV NUMBER_STATUS, AL
    CMP AL, 0
    JE TEST_PIN_VALID
    CMP AL, 1
    JE TEST_PIN_ENDED
    MOV DX, OFFSET MSG_PIN_BAD
    CALL PRINT_STRING
    RET

TEST_PIN_VALID:
    MOV DX, OFFSET MSG_PIN_OK
    CALL PRINT_STRING
    RET

TEST_PIN_ENDED:
    MOV DX, OFFSET MSG_PIN_EOF
    CALL PRINT_STRING
    RET

TEST_ACCTPIN:
    CALL READ_LINE
    OR AL, AL
    JNZ TEST_INPUT_ERROR
    MOV DX, OFFSET MSG_ACCOUNT_PREFIX
    CALL PRINT_STRING
    MOV DX, OFFSET LINE_BUFFER+2
    MOV AH, 09h
    INT 21h
    CALL PRINT_NEWLINE
    CALL READ_PIN
    MOV PIN_STATUS, AL
    MOV NUMBER_STATUS, AL
    CMP AL, 0
    JE TEST_PIN_VALID
    CMP AL, 1
    JE TEST_PIN_ENDED
    MOV DX, OFFSET MSG_PIN_BAD
    CALL PRINT_STRING
    RET

TEST_DECIMAL:
    CALL NEXT_TOKEN
    JC TEST_DECIMAL_BAD
    CALL PARSE_U16
    JC TEST_DECIMAL_BAD
    MOV NUMBER_VALUE, AX
    CALL PRINT_DECIMAL
    CALL PRINT_NEWLINE
    XOR AL, AL
    MOV NUMBER_STATUS, AL
    RET

TEST_DECIMAL_BAD:
    MOV DX, OFFSET MSG_BAD_NUMBER
    CALL PRINT_STRING
    MOV NUMBER_STATUS, 1
    RET

TEST_PSP:
    MOV AH, 62h
    INT 21h
    CMP BX, PSP_SEGMENT
    JNE TEST_PSP_BAD
    MOV DX, OFFSET MSG_PSP_OK
    CALL PRINT_STRING
    XOR AL, AL
    MOV NUMBER_STATUS, AL
    RET

TEST_PSP_BAD:
    MOV DX, OFFSET MSG_PSP_BAD
    CALL PRINT_STRING
    MOV NUMBER_STATUS, 1
    RET

TEST_BCD:
    CALL RUN_BCD_TEST
    RET
RUN_IO_TEST ENDP

; Purpose: Run generated BCD vectors from redirected test input.
; Inputs: Each line contains an operation and its packed-BCD operands or text.
; Outputs: Prints results; NUMBER_STATUS is 0 for completed or 1 for malformed.
; Registers: Destroys AX, BX, CX, DX, SI, DI; preserves BP, DS, ES.
; Flags: Unspecified.
; ISA: CALL, conditional branches, and INT 21h-backed line/string I/O.
RUN_BCD_TEST PROC NEAR
    MOV NUMBER_STATUS, 0
RUN_BCD_NEXT:
    CALL READ_LINE
    CMP AL, 1
    JNE RUN_BCD_HAS_LINE
    JMP RUN_BCD_DONE
RUN_BCD_HAS_LINE:
    OR AL, AL
    JZ RUN_BCD_LINE_OK
    JMP RUN_BCD_INVALID
RUN_BCD_LINE_OK:
    MOV SI, OFFSET LINE_BUFFER+2
    MOV AL, [SI]
    CMP AL, 'A'
    JNE RUN_BCD_NOT_ADD
    JMP RUN_BCD_ADD
RUN_BCD_NOT_ADD:
    CMP AL, 'S'
    JNE RUN_BCD_NOT_SUB
    JMP RUN_BCD_SUB
RUN_BCD_NOT_SUB:
    CMP AL, 'C'
    JNE RUN_BCD_NOT_CMP
    JMP RUN_BCD_CMP
RUN_BCD_NOT_CMP:
    CMP AL, 'F'
    JNE RUN_BCD_NOT_FORMAT
    JMP RUN_BCD_FORMAT
RUN_BCD_NOT_FORMAT:
    CMP AL, 'P'
    JE RUN_BCD_IS_PARSE
    JMP RUN_BCD_INVALID
RUN_BCD_IS_PARSE:
    JMP RUN_BCD_PARSE

RUN_BCD_ADD:
    INC SI
    MOV DI, OFFSET BCD_LEFT
    CALL BCD_TEST_LOAD
    JNC RUN_BCD_ADD_LEFT_OK
    JMP RUN_BCD_INVALID
RUN_BCD_ADD_LEFT_OK:
    MOV DI, OFFSET BCD_RIGHT
    CALL BCD_TEST_LOAD
    JNC RUN_BCD_ADD_RIGHT_OK
    JMP RUN_BCD_INVALID
RUN_BCD_ADD_RIGHT_OK:
    MOV SI, OFFSET BCD_RIGHT
    MOV DI, OFFSET BCD_LEFT
    CALL bcd_add
    MOV BCD_STATUS, 0
    JNC RUN_BCD_ADD_FORMAT
    MOV BCD_STATUS, 1
RUN_BCD_ADD_FORMAT:
    MOV SI, OFFSET BCD_LEFT
    MOV DI, OFFSET BCD_TEXT
    CALL bcd_format
    MOV DX, OFFSET MSG_BCD_ADD
    CALL PRINT_STRING
    MOV DX, OFFSET BCD_TEXT
    CALL PRINT_STRING
    CMP BCD_STATUS, 0
    JNE RUN_BCD_ADD_CARRY
    MOV DX, OFFSET MSG_BCD_CARRY0
    CALL PRINT_STRING
    JMP RUN_BCD_NEXT
RUN_BCD_ADD_CARRY:
    MOV DX, OFFSET MSG_BCD_CARRY1
    CALL PRINT_STRING
    JMP RUN_BCD_NEXT

RUN_BCD_SUB:
    INC SI
    MOV DI, OFFSET BCD_LEFT
    CALL BCD_TEST_LOAD
    JNC RUN_BCD_SUB_LEFT_OK
    JMP RUN_BCD_INVALID
RUN_BCD_SUB_LEFT_OK:
    MOV DI, OFFSET BCD_RIGHT
    CALL BCD_TEST_LOAD
    JNC RUN_BCD_SUB_RIGHT_OK
    JMP RUN_BCD_INVALID
RUN_BCD_SUB_RIGHT_OK:
    MOV SI, OFFSET BCD_RIGHT
    MOV DI, OFFSET BCD_LEFT
    CALL bcd_sub
    MOV BCD_STATUS, 0
    JNC RUN_BCD_SUB_FORMAT
    MOV BCD_STATUS, 1
RUN_BCD_SUB_FORMAT:
    MOV SI, OFFSET BCD_LEFT
    MOV DI, OFFSET BCD_TEXT
    CALL bcd_format
    MOV DX, OFFSET MSG_BCD_SUB
    CALL PRINT_STRING
    MOV DX, OFFSET BCD_TEXT
    CALL PRINT_STRING
    CMP BCD_STATUS, 0
    JNE RUN_BCD_SUB_BORROW
    MOV DX, OFFSET MSG_BCD_BORROW0
    CALL PRINT_STRING
    JMP RUN_BCD_NEXT
RUN_BCD_SUB_BORROW:
    MOV DX, OFFSET MSG_BCD_BORROW1
    CALL PRINT_STRING
    JMP RUN_BCD_NEXT

RUN_BCD_CMP:
    INC SI
    MOV DI, OFFSET BCD_LEFT
    CALL BCD_TEST_LOAD
    JNC RUN_BCD_CMP_LEFT_OK
    JMP RUN_BCD_INVALID
RUN_BCD_CMP_LEFT_OK:
    MOV DI, OFFSET BCD_RIGHT
    CALL BCD_TEST_LOAD
    JNC RUN_BCD_CMP_RIGHT_OK
    JMP RUN_BCD_INVALID
RUN_BCD_CMP_RIGHT_OK:
    MOV SI, OFFSET BCD_LEFT
    MOV DI, OFFSET BCD_RIGHT
    CALL bcd_cmp
    JB RUN_BCD_CMP_LESS
    JE RUN_BCD_CMP_EQUAL
    MOV DX, OFFSET MSG_BCD_GREATER
    CALL PRINT_STRING
    JMP RUN_BCD_NEXT
RUN_BCD_CMP_LESS:
    MOV DX, OFFSET MSG_BCD_LESS
    CALL PRINT_STRING
    JMP RUN_BCD_NEXT
RUN_BCD_CMP_EQUAL:
    MOV DX, OFFSET MSG_BCD_EQUAL
    CALL PRINT_STRING
    JMP RUN_BCD_NEXT

RUN_BCD_FORMAT:
    INC SI
    MOV DI, OFFSET BCD_LEFT
    CALL BCD_TEST_LOAD
    JNC RUN_BCD_FORMAT_VALUE_OK
    JMP RUN_BCD_INVALID
RUN_BCD_FORMAT_VALUE_OK:
    MOV SI, OFFSET BCD_LEFT
    MOV DI, OFFSET BCD_TEXT
    CALL bcd_format
    MOV DX, OFFSET MSG_BCD_FORMAT
    CALL PRINT_STRING
    MOV DX, OFFSET BCD_TEXT
    CALL PRINT_STRING
    CALL PRINT_NEWLINE
    JMP RUN_BCD_NEXT

RUN_BCD_PARSE:
    INC SI
    MOV CX, LINE_COUNT
    DEC CX
    MOV DI, OFFSET BCD_LEFT
    CALL bcd_parse
    CMP AL, 0
    JNE RUN_BCD_PARSE_REJECT
    MOV SI, OFFSET BCD_LEFT
    MOV DI, OFFSET BCD_TEXT
    CALL bcd_format
    MOV DX, OFFSET MSG_BCD_PARSE
    CALL PRINT_STRING
    MOV DX, OFFSET BCD_TEXT
    CALL PRINT_STRING
    CALL PRINT_NEWLINE
    JMP RUN_BCD_NEXT
RUN_BCD_PARSE_REJECT:
    MOV DX, OFFSET MSG_BCD_REJECT
    CALL PRINT_STRING
    JMP RUN_BCD_NEXT

RUN_BCD_INVALID:
    MOV DX, OFFSET MSG_BCD_INVALID
    CALL PRINT_STRING
    MOV NUMBER_STATUS, 1
RUN_BCD_DONE:
    RET
RUN_BCD_TEST ENDP

; Purpose: Load six packed-BCD bytes from twelve decimal characters.
; Inputs: DS:SI points to the first digit; DS:DI points to six output bytes.
; Outputs: Stores six bytes and advances SI by 12 and DI by 6; CF=1 for non-digits.
; Registers: Preserves AX, BX, CX, DX, BP, DS, ES.
; Flags: CF reports invalid input.
; ISA: SHL by one, LOOP, and register-indirect addressing.
BCD_TEST_LOAD PROC NEAR
    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX
    MOV CX, 6
BCD_TEST_LOAD_BYTE:
    MOV AL, [SI]
    CMP AL, '0'
    JB BCD_TEST_LOAD_BAD
    CMP AL, '9'
    JA BCD_TEST_LOAD_BAD
    SUB AL, '0'
    MOV DL, AL
    SHL DL, 1
    SHL DL, 1
    SHL DL, 1
    SHL DL, 1
    INC SI
    MOV AL, [SI]
    CMP AL, '0'
    JB BCD_TEST_LOAD_BAD
    CMP AL, '9'
    JA BCD_TEST_LOAD_BAD
    SUB AL, '0'
    OR AL, DL
    MOV [DI], AL
    INC SI
    INC DI
    LOOP BCD_TEST_LOAD_BYTE
    CLC
    JMP BCD_TEST_LOAD_RETURN
BCD_TEST_LOAD_BAD:
    STC
BCD_TEST_LOAD_RETURN:
    POP DX
    POP CX
    POP BX
    POP AX
    RET
BCD_TEST_LOAD ENDP

