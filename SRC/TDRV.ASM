; Purpose: Run generated BCD vectors from redirected test input.
; Inputs: Each line contains an operation and its packed-BCD operands or text.
; Outputs: Prints results; NUMBER_STATUS is 0 for completed or 1 for malformed.
; Registers: Destroys AX, BX, CX, DX, SI, DI; preserves BP, DS, ES.
; Flags: Unspecified.
; ISA: CALL, conditional branches, and INT 21h-backed line/string I/O.
RUN_BCD_TEST PROC NEAR
    MOV NUMBER_STATUS, 0
RUN_BCD_NEXT:
    CALL READ_LINE
    CMP AL, 1
    JNE RUN_BCD_HAS_LINE
    JMP RUN_BCD_DONE
RUN_BCD_HAS_LINE:
    OR AL, AL
    JZ RUN_BCD_LINE_OK
    JMP RUN_BCD_INVALID
RUN_BCD_LINE_OK:
    MOV SI, OFFSET LINE_BUFFER+2
    MOV AL, [SI]
    CMP AL, 'A'
    JNE RUN_BCD_NOT_ADD
    JMP RUN_BCD_ADD
RUN_BCD_NOT_ADD:
    CMP AL, 'S'
    JNE RUN_BCD_NOT_SUB
    JMP RUN_BCD_SUB
RUN_BCD_NOT_SUB:
    CMP AL, 'C'
    JNE RUN_BCD_NOT_CMP
    JMP RUN_BCD_CMP
RUN_BCD_NOT_CMP:
    CMP AL, 'F'
    JNE RUN_BCD_NOT_FORMAT
    JMP RUN_BCD_FORMAT
RUN_BCD_NOT_FORMAT:
    CMP AL, 'P'
    JE RUN_BCD_IS_PARSE
    JMP RUN_BCD_INVALID
RUN_BCD_IS_PARSE:
    JMP RUN_BCD_PARSE

RUN_BCD_ADD:
    INC SI
    MOV DI, OFFSET BCD_LEFT
    CALL BCD_TEST_LOAD
    JNC RUN_BCD_ADD_LEFT_OK
    JMP RUN_BCD_INVALID
RUN_BCD_ADD_LEFT_OK:
    MOV DI, OFFSET BCD_RIGHT
    CALL BCD_TEST_LOAD
    JNC RUN_BCD_ADD_RIGHT_OK
    JMP RUN_BCD_INVALID
RUN_BCD_ADD_RIGHT_OK:
    MOV SI, OFFSET BCD_RIGHT
    MOV DI, OFFSET BCD_LEFT
    CALL bcd_add
    MOV BCD_STATUS, 0
    JNC RUN_BCD_ADD_FORMAT
    MOV BCD_STATUS, 1
RUN_BCD_ADD_FORMAT:
    MOV SI, OFFSET BCD_LEFT
    MOV DI, OFFSET BCD_TEXT
    CALL bcd_format
    MOV DX, OFFSET MSG_BCD_ADD
    CALL PRINT_STRING
    MOV DX, OFFSET BCD_TEXT
    CALL PRINT_STRING
    CMP BCD_STATUS, 0
    JNE RUN_BCD_ADD_CARRY
    MOV DX, OFFSET MSG_BCD_CARRY0
    CALL PRINT_STRING
    JMP RUN_BCD_NEXT
RUN_BCD_ADD_CARRY:
    MOV DX, OFFSET MSG_BCD_CARRY1
    CALL PRINT_STRING
    JMP RUN_BCD_NEXT

RUN_BCD_SUB:
    INC SI
    MOV DI, OFFSET BCD_LEFT
    CALL BCD_TEST_LOAD
    JNC RUN_BCD_SUB_LEFT_OK
    JMP RUN_BCD_INVALID
RUN_BCD_SUB_LEFT_OK:
    MOV DI, OFFSET BCD_RIGHT
    CALL BCD_TEST_LOAD
    JNC RUN_BCD_SUB_RIGHT_OK
    JMP RUN_BCD_INVALID
RUN_BCD_SUB_RIGHT_OK:
    MOV SI, OFFSET BCD_RIGHT
    MOV DI, OFFSET BCD_LEFT
    CALL bcd_sub
    MOV BCD_STATUS, 0
    JNC RUN_BCD_SUB_FORMAT
    MOV BCD_STATUS, 1
RUN_BCD_SUB_FORMAT:
    MOV SI, OFFSET BCD_LEFT
    MOV DI, OFFSET BCD_TEXT
    CALL bcd_format
    MOV DX, OFFSET MSG_BCD_SUB
    CALL PRINT_STRING
    MOV DX, OFFSET BCD_TEXT
    CALL PRINT_STRING
    CMP BCD_STATUS, 0
    JNE RUN_BCD_SUB_BORROW
    MOV DX, OFFSET MSG_BCD_BORROW0
    CALL PRINT_STRING
    JMP RUN_BCD_NEXT
RUN_BCD_SUB_BORROW:
    MOV DX, OFFSET MSG_BCD_BORROW1
    CALL PRINT_STRING
    JMP RUN_BCD_NEXT

RUN_BCD_CMP:
    INC SI
    MOV DI, OFFSET BCD_LEFT
    CALL BCD_TEST_LOAD
    JNC RUN_BCD_CMP_LEFT_OK
    JMP RUN_BCD_INVALID
RUN_BCD_CMP_LEFT_OK:
    MOV DI, OFFSET BCD_RIGHT
    CALL BCD_TEST_LOAD
    JNC RUN_BCD_CMP_RIGHT_OK
    JMP RUN_BCD_INVALID
RUN_BCD_CMP_RIGHT_OK:
    MOV SI, OFFSET BCD_LEFT
    MOV DI, OFFSET BCD_RIGHT
    CALL bcd_cmp
    JB RUN_BCD_CMP_LESS
    JE RUN_BCD_CMP_EQUAL
    MOV DX, OFFSET MSG_BCD_GREATER
    CALL PRINT_STRING
    JMP RUN_BCD_NEXT
RUN_BCD_CMP_LESS:
    MOV DX, OFFSET MSG_BCD_LESS
    CALL PRINT_STRING
    JMP RUN_BCD_NEXT
RUN_BCD_CMP_EQUAL:
    MOV DX, OFFSET MSG_BCD_EQUAL
    CALL PRINT_STRING
    JMP RUN_BCD_NEXT

RUN_BCD_FORMAT:
    INC SI
    MOV DI, OFFSET BCD_LEFT
    CALL BCD_TEST_LOAD
    JNC RUN_BCD_FORMAT_VALUE_OK
    JMP RUN_BCD_INVALID
RUN_BCD_FORMAT_VALUE_OK:
    MOV SI, OFFSET BCD_LEFT
    MOV DI, OFFSET BCD_TEXT
    CALL bcd_format
    MOV DX, OFFSET MSG_BCD_FORMAT
    CALL PRINT_STRING
    MOV DX, OFFSET BCD_TEXT
    CALL PRINT_STRING
    CALL PRINT_NEWLINE
    JMP RUN_BCD_NEXT

RUN_BCD_PARSE:
    INC SI
    MOV CX, LINE_COUNT
    DEC CX
    MOV DI, OFFSET BCD_LEFT
    CALL bcd_parse
    CMP AL, 0
    JNE RUN_BCD_PARSE_REJECT
    MOV SI, OFFSET BCD_LEFT
    MOV DI, OFFSET BCD_TEXT
    CALL bcd_format
    MOV DX, OFFSET MSG_BCD_PARSE
    CALL PRINT_STRING
    MOV DX, OFFSET BCD_TEXT
    CALL PRINT_STRING
    CALL PRINT_NEWLINE
    JMP RUN_BCD_NEXT
RUN_BCD_PARSE_REJECT:
    MOV DX, OFFSET MSG_BCD_REJECT
    CALL PRINT_STRING
    JMP RUN_BCD_NEXT

RUN_BCD_INVALID:
    MOV DX, OFFSET MSG_BCD_INVALID
    CALL PRINT_STRING
    MOV NUMBER_STATUS, 1
RUN_BCD_DONE:
    RET
RUN_BCD_TEST ENDP

; Purpose: Load six packed-BCD bytes from twelve decimal characters.
; Inputs: DS:SI points to the first digit; DS:DI points to six output bytes.
; Outputs: Stores six bytes and advances SI by 12 and DI by 6; CF=1 for non-digits.
; Registers: Preserves AX, BX, CX, DX, BP, DS, ES.
; Flags: CF reports invalid input.
; ISA: SHL by one, LOOP, and register-indirect addressing.
BCD_TEST_LOAD PROC NEAR
    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX
    MOV CX, 6
BCD_TEST_LOAD_BYTE:
    MOV AL, [SI]
    CMP AL, '0'
    JB BCD_TEST_LOAD_BAD
    CMP AL, '9'
    JA BCD_TEST_LOAD_BAD
    SUB AL, '0'
    MOV DL, AL
    SHL DL, 1
    SHL DL, 1
    SHL DL, 1
    SHL DL, 1
    INC SI
    MOV AL, [SI]
    CMP AL, '0'
    JB BCD_TEST_LOAD_BAD
    CMP AL, '9'
    JA BCD_TEST_LOAD_BAD
    SUB AL, '0'
    OR AL, DL
    MOV [DI], AL
    INC SI
    INC DI
    LOOP BCD_TEST_LOAD_BYTE
    CLC
    JMP BCD_TEST_LOAD_RETURN
BCD_TEST_LOAD_BAD:
    STC
BCD_TEST_LOAD_RETURN:
    POP DX
    POP CX
    POP BX
    POP AX
    RET
BCD_TEST_LOAD ENDP

END MAIN
